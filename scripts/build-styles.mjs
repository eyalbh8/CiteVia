import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, watch } from 'node:fs';
import { basename, extname } from 'node:path';
import postcss from 'postcss';
import { transform } from 'lightningcss';

export const styleSources = [
  'src/app/site-base.css',
  'src/app/arielos-source.css',
  'src/app/arielos-theme.css',
];

// The first screen and persistent navigation must be complete before the full CSS arrives.
const criticalClass =
  /^(arielos-(home|chrome)|home-page|site-main|site-header.*|nav.*|brand.*|citevia-symbol|hero.*|shell|section(--[a-z-]+)?|platform-marquee.*|footer|button.*|floating-.*|scroll-progress|skip-link|sr-only|visually-hidden|is-.*)$/;

const positionedImageContainers = new Set([
  '.arielos-home .service-photo',
  '.arielos-home .footer__cta',
]);

export function extractCriticalCss(css) {
  const root = postcss.parse(css);
  root.walkComments((node) => node.remove());
  root.walkRules((rule) => {
    if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
    const selectors = rule.selectors.filter((selector) => {
      const classes = [...selector.matchAll(/\.([a-zA-Z_][\w-]*)/g)].map((match) => match[1]);
      return classes.every((name) => criticalClass.test(name));
    });
    if (selectors.length) rule.selectors = selectors;
    else {
      // Fill images need containing blocks immediately, but these offscreen
      // sections must not pull their typography into the first-screen font chain.
      const containers = rule.selectors.filter((selector) =>
        positionedImageContainers.has(selector),
      );
      if (!containers.length) rule.remove();
      else {
        rule.selectors = containers;
        rule.walkDecls((decl) => {
          if (decl.prop !== 'position') decl.remove();
        });
      }
    }
  });
  const animations = new Set();
  root.walkDecls(/^animation(-name)?$/, (decl) => {
    for (const name of decl.value.match(/citevia-[\w-]+/g) || []) animations.add(name);
  });
  root.walkAtRules(/keyframes$/, (rule) => {
    if (!animations.has(rule.params)) rule.remove();
  });
  // Remove empty nested media/support/layer blocks from the inside out.
  const prune = (node) => {
    for (const child of [...(node.nodes || [])]) {
      prune(child);
      if (child.nodes?.length === 0) child.remove();
    }
  };
  prune(root);
  return root.toString();
}

function writeIfChanged(path, contents) {
  try {
    if (readFileSync(path).equals(Buffer.from(contents))) return;
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  writeFileSync(path, contents);
}

export function buildStyles() {
  mkdirSync('public/site-assets', { recursive: true });
  mkdirSync('src/generated', { recursive: true });
  const asset = (name, contents) => {
    const hash = createHash('sha256').update(contents).digest('hex').slice(0, 16);
    const extension = extname(name);
    const href = `/site-assets/${basename(name, extension)}.${hash}${extension}`;
    writeIfChanged(`public${href}`, contents);
    return href;
  };
  const faces = [];
  const font = (family, path, weight, style = 'normal', display = 'optional') => {
    const href = asset(basename(path), readFileSync(path));
    faces.push(
      `@font-face{font-family:'${family}';src:url('${href}') format('woff2');font-weight:${weight};font-style:${style};font-display:${display}}`,
    );
    return href;
  };
  for (const weight of [300, 400, 500, 600, 700, 800, 900]) {
    font(
      'Citevia Open Sauce',
      `public/fonts/arielos/open-sauce-one-latin-${weight}-normal.woff2`,
      weight,
    );
  }
  for (const weight of [500, 600, 700]) {
    font('Citevia Poppins', `public/fonts/arielos/poppins-latin-${weight}-normal.woff2`, weight);
  }
  font(
    'Citevia Instrument',
    'node_modules/@fontsource/instrument-serif/files/instrument-serif-latin-400-normal.woff2',
    400,
    'normal',
    'swap',
  );
  font(
    'Citevia Instrument',
    'node_modules/@fontsource/instrument-serif/files/instrument-serif-latin-400-italic.woff2',
    400,
    'italic',
    'swap',
  );
  // First-screen fonts retain kerning; complete faces cover other glyphs.
  const subsets = JSON.parse(readFileSync('public/fonts/critical/subsets.json', 'utf8'));
  for (const { family, file, weight, unicodeRange } of subsets) {
    const data = readFileSync(`public/fonts/critical/${file}`).toString('base64');
    faces.push(
      `@font-face{font-family:'${family}';src:url('data:font/woff2;base64,${data}') format('woff2');font-weight:${weight};font-style:normal;font-display:swap;unicode-range:${unicodeRange}}`,
    );
  }
  // Preserve the metric adjustments generated by next/font for these unchanged font files.
  faces.push(`
    @font-face{font-family:'Citevia Open Sauce Fallback';src:local(Arial);ascent-override:90.93%;descent-override:21.55%;line-gap-override:0%;size-adjust:109.98%}
    @font-face{font-family:'Citevia Poppins Fallback';src:local(Arial);ascent-override:91.82%;descent-override:30.61%;line-gap-override:8.74%;size-adjust:114.36%}
    @font-face{font-family:'Citevia Instrument Fallback';src:local('Times New Roman');ascent-override:117.87%;descent-override:36.91%;line-gap-override:0%;size-adjust:83.99%}
    :root{--font-open-sauce:'Citevia Open Sauce','Citevia Open Sauce Fallback';--font-poppins:'Citevia Poppins','Citevia Poppins Fallback';--font-instrument:'Citevia Instrument','Citevia Instrument Fallback'}
  `);
  const css = styleSources.map((path) => readFileSync(path, 'utf8')).join('\n');
  const minify = (text) =>
    transform({ filename: 'site.css', code: Buffer.from(text), minify: true }).code.toString();
  const stylesheet = asset('site.css', minify(css));
  const criticalCss = minify(faces.join('\n') + extractCriticalCss(css));
  writeIfChanged(
    'src/generated/site-styles.ts',
    `// Generated by scripts/build-styles.mjs; edit the CSS sources, not this file.\nexport const criticalCss = ${JSON.stringify(criticalCss)};\nexport const stylesheet = ${JSON.stringify(stylesheet)};\n`,
  );
}

if (process.argv[1]?.endsWith('/build-styles.mjs')) {
  buildStyles();
  if (process.argv.includes('--watch')) {
    for (const path of styleSources) watch(path, buildStyles);
  }
}
